"""
login.py - Kotak Neo API Authentication Script

This script performs basic login into Kotak Neo broker using the official
Kotak Neo API SDK (neo_api_client).

Authentication Flow:
1. Consumer Key (API Key / Application Token) initialized with NeoAPI.
2. Step 1: totp_login() with mobile number, UCC, and 6-digit TOTP.
3. Step 2: totp_validate() with 6-digit MPIN for full trading session.
4. On success, extracts and displays the client's name and account details.

Can be run directly:
    python login.py

Or imported into your trading scripts:
    from login import get_client, login
    client = login()
"""

import getpass
import os
import sys
from pathlib import Path
from typing import Any, Dict, Optional, Tuple

import pyotp

# Enable ANSI colors & UTF-8 in Windows Command Prompt (cmd.exe)
if sys.platform == "win32":
    os.system("")  # Initializes Windows console virtual terminal processing
    try:
        if hasattr(sys.stdout, "reconfigure"):
            sys.stdout.reconfigure(encoding="utf-8", errors="replace")
        if hasattr(sys.stderr, "reconfigure"):
            sys.stderr.reconfigure(encoding="utf-8", errors="replace")
    except Exception:
        pass

# Ensure root directory is in sys.path so neo_api_client is discoverable
CURRENT_DIR = Path(__file__).resolve().parent
if str(CURRENT_DIR) not in sys.path:
    sys.path.insert(0, str(CURRENT_DIR))

try:
    from neo_api_client import NeoAPI
except ImportError as err:
    print(
        f"\n[ERROR] Failed to import 'neo_api_client': {err}\n"
        "Please ensure the SDK is available in the project directory or installed via:\n"
        "    pip install kotakneoapi\n"
    )
    sys.exit(1)


# =====================================================================
# Terminal Formatting
# =====================================================================
class Colors:
    HEADER = "\033[95m"
    BLUE = "\033[94m"
    CYAN = "\033[96m"
    GREEN = "\033[92m"
    YELLOW = "\033[93m"
    RED = "\033[91m"
    BOLD = "\033[1m"
    DIM = "\033[2m"
    RESET = "\033[0m"


def print_banner(title: str, color: str = Colors.CYAN) -> None:
    width = 62
    border = "=" * width
    print(f"\n{color}{border}")
    print(f" {title.center(width - 2)} ")
    print(f"{border}{Colors.RESET}")


# =====================================================================
# Environment / .env Helper
# =====================================================================
def load_env_file(filepath: Optional[Path] = None) -> Dict[str, str]:
    """
    Simple .env file loader that reads KEY=VALUE pairs into os.environ.
    Does not require external dotenv dependency, though respects existing env vars.
    """
    if filepath is None:
        candidate = CURRENT_DIR / ".env"
        if candidate.is_file():
            filepath = candidate

    env_vars: Dict[str, str] = {}
    if filepath and filepath.is_file():
        try:
            with open(filepath, "r", encoding="utf-8") as f:
                for line in f:
                    line = line.strip()
                    if not line or line.startswith("#") or "=" not in line:
                        continue
                    key, val = line.split("=", 1)
                    key = key.strip()
                    val = val.strip().strip("'\"")
                    env_vars[key] = val
                    if key not in os.environ:
                        os.environ[key] = val
        except Exception as e:
            print(f"{Colors.YELLOW}[!] Warning: Could not read .env file: {e}{Colors.RESET}")

    return env_vars


def save_credentials_to_env(
    consumer_key: str,
    mobile_number: str,
    ucc: str,
    mpin: str,
    totp_secret: Optional[str] = None,
    filepath: Optional[Path] = None,
) -> None:
    """Save provided credentials to .env file for future automatic logins."""
    if filepath is None:
        filepath = CURRENT_DIR / ".env"

    content = [
        "# Kotak Neo API Credentials",
        "# Generated by login.py",
        f"NEO_CONSUMER_KEY={consumer_key}",
        f"NEO_MOBILE_NUMBER={mobile_number}",
        f"NEO_UCC={ucc}",
        f"NEO_MPIN={mpin}",
    ]
    if totp_secret:
        content.append(f"NEO_TOTP_SECRET={totp_secret}")

    content.append("NEO_ENVIRONMENT=prod\n")

    try:
        with open(filepath, "w", encoding="utf-8") as f:
            f.write("\n".join(content))
        print(f"{Colors.GREEN}[OK] Credentials saved to {filepath}{Colors.RESET}")
    except Exception as e:
        print(f"{Colors.YELLOW}[!] Could not save to .env: {e}{Colors.RESET}")


def normalize_mobile(mobile: str) -> str:
    """Ensure mobile number has country code format, e.g. +919876543210."""
    mobile = mobile.strip().replace(" ", "").replace("-", "")
    if mobile.startswith("+"):
        return mobile
    if len(mobile) == 10 and mobile.isdigit():
        return f"+91{mobile}"
    if len(mobile) == 12 and mobile.startswith("91") and mobile.isdigit():
        return f"+{mobile}"
    return mobile


# =====================================================================
# Credential Gathering (Interactive + .env fallback)
# =====================================================================
def prompt_or_env(
    env_name: str,
    prompt_text: str,
    default: Optional[str] = None,
    is_secret: bool = False,
    help_text: Optional[str] = None,
) -> str:
    """Fetch value from os.environ or prompt user interactively."""
    env_val = os.environ.get(env_name, "").strip()
    if env_val:
        # Value exists in environment
        masked = "*" * len(env_val) if is_secret else env_val
        print(f"{Colors.DIM}Using {env_name} from environment: {masked}{Colors.RESET}")
        return env_val

    if help_text:
        print(f"{Colors.DIM}INFO: {help_text}{Colors.RESET}")

    while True:
        display_prompt = f"{prompt_text}"
        if default:
            display_prompt += f" [{default}]"
        display_prompt += ": "

        if is_secret:
            try:
                val = getpass.getpass(display_prompt).strip()
            except Exception:
                val = input(display_prompt).strip()
        else:
            val = input(display_prompt).strip()

        if not val and default:
            val = default

        if val:
            return val
        print(f"{Colors.RED}This field is required. Please try again.{Colors.RESET}")


def get_totp_code(totp_secret: Optional[str] = None) -> str:
    """
    Generate 6-digit TOTP code using totp_secret if available,
    otherwise prompt user to enter the code from their authenticator app.
    """
    if totp_secret:
        try:
            totp = pyotp.TOTP(totp_secret.strip())
            code = totp.now()
            print(f"{Colors.GREEN}[OK] Auto-generated TOTP using secret: {code}{Colors.RESET}")
            return code
        except Exception as e:
            print(f"{Colors.YELLOW}[!] Failed to generate TOTP from secret: {e}{Colors.RESET}")

    # Prompt user for manual TOTP
    while True:
        code = input(
            f"{Colors.BOLD}Enter 6-digit TOTP code from Authenticator app: {Colors.RESET}"
        ).strip()
        if len(code) == 6 and code.isdigit():
            return code
        print(f"{Colors.RED}Invalid TOTP code. It must be a 6-digit number.{Colors.RESET}")


def extract_error_message(response: Any) -> str:
    """Extract a user-friendly error message from API response dictionary."""
    if not isinstance(response, dict):
        return str(response)

    # Kotak Neo standard error format: {"error": [{"code": "...", "message": "..."}]}
    errors = response.get("error")
    if isinstance(errors, list) and errors:
        first_err = errors[0]
        if isinstance(first_err, dict):
            code = first_err.get("code", "")
            msg = first_err.get("message", "")
            return f"[{code}] {msg}" if code else msg
        return str(errors)

    if "Error" in response:
        return str(response.get("Error"))

    if "Error Message" in response:
        return str(response.get("Error Message"))

    if "message" in response:
        return str(response.get("message"))

    data = response.get("data")
    if isinstance(data, dict):
        if data.get("status") == "failed":
            return data.get("message") or "Authentication failed"

    return str(response)


# =====================================================================
# Main Login Routine
# =====================================================================
def login(
    consumer_key: Optional[str] = None,
    mobile_number: Optional[str] = None,
    ucc: Optional[str] = None,
    mpin: Optional[str] = None,
    totp: Optional[str] = None,
    totp_secret: Optional[str] = None,
    environment: str = "prod",
    save_to_env: bool = False,
    show_limits: bool = True,
) -> Tuple[NeoAPI, Dict[str, Any]]:
    """
    Authenticate with Kotak Neo API and return (client, user_profile).

    Parameters:
        consumer_key: API Application token from Kotak Neo web/app (Trade API card)
        mobile_number: Registered mobile number (e.g. +919876543210)
        ucc: Unique Client Code
        mpin: 6-digit trading MPIN
        totp: 6-digit current TOTP code (optional if totp_secret is supplied)
        totp_secret: Base32 TOTP secret key for automatic TOTP generation
        environment: 'prod' (default) or 'uat'
        save_to_env: If True, saves credentials to .env file for future runs
        show_limits: If True, fetches and displays available cash & limits after login

    Returns:
        Tuple of (authenticated NeoAPI instance, user profile dict)
    """
    # Load .env file if available
    load_env_file()

    print_banner("KOTAK NEO BROKER LOGIN", Colors.CYAN)
    print("Kotak Neo API Authentication\n")

    # 1. Consumer Key (API Key)
    if not consumer_key:
        consumer_key = prompt_or_env(
            env_name="NEO_CONSUMER_KEY",
            prompt_text="Enter Consumer Key (API Token)",
            is_secret=True,
            help_text="Find in Kotak Neo App/Web -> More -> Trade API -> Generate Application",
        )

    # 2. Registered Mobile Number
    if not mobile_number:
        raw_mobile = prompt_or_env(
            env_name="NEO_MOBILE_NUMBER",
            prompt_text="Enter Registered Mobile Number (e.g. 9876543210)",
            help_text="Registered 10-digit mobile number with Kotak Neo",
        )
        mobile_number = normalize_mobile(raw_mobile)
    else:
        mobile_number = normalize_mobile(mobile_number)

    # 3. User Client Code (UCC)
    if not ucc:
        ucc = prompt_or_env(
            env_name="NEO_UCC",
            prompt_text="Enter UCC (User Client Code)",
            help_text="Find in Kotak Neo App/Web under Profile section",
        ).upper()
    else:
        ucc = ucc.upper()

    # 4. TOTP Secret (optional, for auto-generating TOTP)
    if not totp_secret and not totp:
        totp_secret = os.environ.get("NEO_TOTP_SECRET", "").strip() or None

    # 5. TOTP Code (Step 1)
    if not totp:
        totp = get_totp_code(totp_secret)

    # 6. MPIN (Step 2)
    if not mpin:
        mpin = prompt_or_env(
            env_name="NEO_MPIN",
            prompt_text="Enter 6-digit Trading MPIN",
            is_secret=True,
            help_text="Your 6-digit Trading MPIN used for Kotak Neo 2FA",
        )

    # 7. Environment
    if not environment:
        environment = os.environ.get("NEO_ENVIRONMENT", "prod").strip() or "prod"

    # -----------------------------------------------------------------
    # Step 1: Initialize NeoAPI Client
    # -----------------------------------------------------------------
    print(f"\n{Colors.BLUE}[1/3] Initializing Kotak Neo API client (env: {environment})...{Colors.RESET}")
    try:
        client = NeoAPI(
            consumer_key=consumer_key,
            environment=environment,
        )
    except Exception as e:
        print(f"{Colors.RED}[X] Failed to initialize NeoAPI client: {e}{Colors.RESET}")
        raise

    # -----------------------------------------------------------------
    # Step 2: TOTP Login (Generate View Token)
    # -----------------------------------------------------------------
    print(f"{Colors.BLUE}[2/3] Performing TOTP Login (Mobile: {mobile_number}, UCC: {ucc})...{Colors.RESET}")
    try:
        totp_login_res = client.totp_login(
            mobile_number=mobile_number,
            ucc=ucc,
            totp=totp,
        )
    except Exception as e:
        print(f"{Colors.RED}[X] Network or API exception during totp_login: {e}{Colors.RESET}")
        raise

    # Validate Step 1 Response
    if not isinstance(totp_login_res, dict) or "error" in totp_login_res or "Error" in totp_login_res:
        err_msg = extract_error_message(totp_login_res)
        print(f"\n{Colors.RED}[X] TOTP Login Failed: {err_msg}{Colors.RESET}")
        print(f"{Colors.DIM}Please verify your Mobile Number, UCC, and 6-digit TOTP code.{Colors.RESET}\n")
        raise RuntimeError(f"TOTP Login failed: {err_msg}")

    login_data = totp_login_res.get("data")
    if not login_data or not isinstance(login_data, dict) or not login_data.get("token"):
        err_msg = extract_error_message(totp_login_res)
        print(f"\n{Colors.RED}[X] TOTP Login Failed: {err_msg}{Colors.RESET}\n")
        raise RuntimeError(f"TOTP Login failed: {err_msg}")

    # View token acquired
    view_client_name = login_data.get("greetingName", "N/A")
    print(f"{Colors.GREEN}[OK] Step 1 Successful! View session created for: {view_client_name}{Colors.RESET}")

    # -----------------------------------------------------------------
    # Step 3: MPIN Validation (Generate Trade Token with Full Access)
    # -----------------------------------------------------------------
    print(f"{Colors.BLUE}[3/3] Validating MPIN for Full Trading Access...{Colors.RESET}")
    try:
        validate_res = client.totp_validate(mpin=mpin)
    except Exception as e:
        print(f"{Colors.RED}[X] Network or API exception during totp_validate: {e}{Colors.RESET}")
        raise

    # Validate Step 2 Response
    if not isinstance(validate_res, dict) or "error" in validate_res or "Error" in validate_res:
        err_msg = extract_error_message(validate_res)
        print(f"\n{Colors.RED}[X] MPIN Validation Failed: {err_msg}{Colors.RESET}")
        print(f"{Colors.DIM}Please check if your 6-digit MPIN is correct.{Colors.RESET}\n")
        raise RuntimeError(f"MPIN validation failed: {err_msg}")

    trade_data = validate_res.get("data")
    if not trade_data or not isinstance(trade_data, dict) or not trade_data.get("token"):
        err_msg = extract_error_message(validate_res)
        print(f"\n{Colors.RED}[X] MPIN Validation Failed: {err_msg}{Colors.RESET}\n")
        raise RuntimeError(f"MPIN validation failed: {err_msg}")

    # -----------------------------------------------------------------
    # Extract Client Profile Information
    # -----------------------------------------------------------------
    # greetingName is the name of the client returned by Kotak Neo
    client_name = trade_data.get("greetingName") or login_data.get("greetingName") or "Client"
    client_ucc = trade_data.get("ucc") or ucc
    pan_kid = trade_data.get("kId", "N/A")
    client_type = trade_data.get("clientType", "Retail")
    access_type = trade_data.get("kType", "Trade")
    data_center = trade_data.get("dataCenter", "N/A")
    session_id = trade_data.get("sid", "N/A")
    account_status = trade_data.get("dormancyStatus", "Active")

    # Mask PAN card for display privacy (e.g. ABCDE1234F -> ABCDE****F)
    masked_pan = pan_kid
    if len(pan_kid) == 10:
        masked_pan = f"{pan_kid[:5]}****{pan_kid[-1]}"

    # -----------------------------------------------------------------
    # Display Successful Login Card
    # -----------------------------------------------------------------
    print_banner("LOGIN SUCCESSFUL", Colors.GREEN)
    print(f"  {Colors.BOLD}Client Name   :{Colors.RESET} {Colors.GREEN}{Colors.BOLD}{client_name}{Colors.RESET}")
    print(f"  {Colors.BOLD}Client UCC    :{Colors.RESET} {client_ucc}")
    print(f"  {Colors.BOLD}PAN Card      :{Colors.RESET} {masked_pan}")
    print(f"  {Colors.BOLD}Client Type   :{Colors.RESET} {client_type}")
    print(f"  {Colors.BOLD}Access Level  :{Colors.RESET} {access_type} (Full Trading Access)")
    print(f"  {Colors.BOLD}Data Center   :{Colors.RESET} {data_center}")
    print(f"  {Colors.BOLD}Session ID    :{Colors.RESET} {session_id[:16]}...")
    print(f"  {Colors.BOLD}Account Status:{Colors.RESET} {'Active' if account_status == 'A' else account_status}")
    print("=" * 62)

    # -----------------------------------------------------------------
    # Optional: Fetch Available Limits / Cash Balance
    # -----------------------------------------------------------------
    if show_limits:
        try:
            print(f"\n{Colors.DIM}Fetching account limits & margin details...{Colors.RESET}")
            limits_res = client.limits()
            if isinstance(limits_res, dict) and "error" not in limits_res and "Error" not in limits_res:
                net_cash = limits_res.get("Net", limits_res.get("AvailableCash", limits_res.get("CashBalance", "N/A")))
                collateral = limits_res.get("CollateralValue", "0.00")
                margin_used = limits_res.get("MarginUsed", "0.00")
                print(f"  Available Margin/Cash : Rs. {net_cash}")
                if collateral != "0.00":
                    print(f"  Collateral Value      : Rs. {collateral}")
                if margin_used != "0.00":
                    print(f"  Margin Utilized       : Rs. {margin_used}")
        except Exception:
            # Limits display is best-effort and must not fail the login flow
            pass

    # Save to .env if requested
    if save_to_env:
        save_credentials_to_env(
            consumer_key=consumer_key,
            mobile_number=mobile_number,
            ucc=client_ucc,
            mpin=mpin,
            totp_secret=totp_secret,
        )

    profile_info = {
        "client_name": client_name,
        "ucc": client_ucc,
        "pan": pan_kid,
        "client_type": client_type,
        "access_type": access_type,
        "data_center": data_center,
        "session_id": session_id,
        "raw_response": trade_data,
    }

    return client, profile_info


def get_client() -> NeoAPI:
    """Convenience helper to obtain an authenticated client."""
    client, _ = login()
    return client


# =====================================================================
# CLI Entry Point
# =====================================================================
if __name__ == "__main__":
    try:
        authenticated_client, user_info = login()
        print(f"\n{Colors.GREEN}[OK] Authentication complete. Ready for trading!{Colors.RESET}\n")
    except KeyboardInterrupt:
        print(f"\n{Colors.YELLOW}[!] Login cancelled by user.{Colors.RESET}")
        sys.exit(0)
    except Exception as exc:
        print(f"\n{Colors.RED}[X] Login failed: {exc}{Colors.RESET}")
        sys.exit(1)
